# A designated split allways increases the relationship between the variable "X" and "Y".
# Both "X" and "Y" have values in [0,1].
# The split can take place in “X” and “Y” as well as in a third or fourth variable “Kn” or “Kt”.
# "Kn” is a continuous variable with values in [0,1].
# "Kt" is a categorical variable with attributes {"A", "B", "C", "D", "E"}.


seed_val = None
# To generate pseudo-random, reproducible results.
# The following function is used to increase the local seed value by 1 ...
# ... after each application of a random realization ...
# ... so that all realizations/variables are different:
def SEED():
    global seed_val
    np.random.seed(seed_val)
    seed_val = seed_val + 1 if seed_val is not None else seed_val



depth_faktor = 2/3
type_list = ["lin", "squ", "cub", "exp", "srt", "sin", "ggk"]


# Automated plot of the data set using seaborn pairplot:
def print_dataset(df):
    sns.pairplot(df, diag_kind="kde", plot_kws=dict(marker="x", alpha = 0.9, linewidth=0.08))
    plt.show()


