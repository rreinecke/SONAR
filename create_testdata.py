def create_X(r_S, printit = False, type ="lin"):
    df = create_dataset(r_S= r_S, type = type)                  # Partial data set with existing relationship
    df["X"] = df["X"]/10                                        # Applying the threshold value (X ≤ 0.1)
    SEED(); x1_rand = np.random.randint(1001,10001, 9000)/10000 # Generating the remaining data set
    SEED(); x2_rand = np.random.randint(1,10001, 9000)/10000
    df_append = pd.DataFrame({'X': x1_rand, 'Y': x2_rand})      # Combine both partial data sets
    df = pd.concat([df, df_append], ignore_index= True)
    if printit: print_dataset(df)
    return df

