# Secondly, the data sets that already have two designated splits are generated.
# Since the relationship between X and Y in the partial data set after two splits should follow...
#    ... the same, modified regression curve as the one from the partial data set after one split, ...
#    ... the previously defined functions would be difficult to implement. Therefore, each of ...
#    ... the following functions constructs the high-functional relationship already according to the ...
#    ... regression curve of the partial data set with the weakest relationship (see subsection 3.3.1).
# As the creation is done “from the back to the front”, the second split is already defined...
#    ... for a particular function, while the first split is variable:


