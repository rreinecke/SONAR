# Aggregation of all possible combinations in the creation of a test data set in one shared function:

# The function takes the specifications according to Table 3.3 as input and returns the corresponding data set
def test_data(split1, split2, split3, r_S, printit = False, type ="lin", interf_var = False, seed = None):
    # Check the arguments for possible splits:
    if ((split1 not in ["O", "X", "Kn", "Kt", "Y"]) or (split2 not in ["O", "X", "Kn", "Kt", "Y"])
            or (split3 not in ["X", "Kn", "Kt", "Y"])):
        print("Wrong input")
        return
    if (split1 == split2) or (split1 == split3) or (split2 == split3):
        if not ((split1 == "O") and (split2 == "O")):
            print("Split variables must be different in pairs.")
            return

    # Check the value range for the strength and the type of the relationship
    if (r_S < -1) or (r_S > 1):
        print("Correlation value (Pearson r) must be between -1 and 1.")
        return
    if type not in ["lin", "squ", "cub", "exp", "srt", "sin", "ggk"]:
        print("Function type must be one of the following: 'lin', 'squ', 'cub', 'exp', 'srt', 'sin' or 'ggk'.")
        return

    # Acquiring the global seed
    global seed_val; seed_val = seed

    # Calling the previous functions, depending on the number of splits:
    if (split1 == "O") and (split2 == "O"):
        function_name = f"create_{split3}"
        func = globals()[function_name]
        df = func(r_S = r_S, type = type)

    elif (split1 == "O") and (split2 != "O"):
        function_name = f"create_var1_{split3}"
        func = globals()[function_name]
        df = func(r_S = r_S, var1 = split2, type = type)

    elif (split1 != "O") and (split2 != "O"):
        function_name = f"create_var1_var2_{split3}"
        func = globals()[function_name]
        df = func(r_S = r_S, var1 = split1, var2 = split2, type = type)

    else: # when split1 == "O" and split2 ≠ 0
        print("Wrong input. Split2 can't be 'O', when split1 ≠ O.")
        return

    size = len(df)

    # Convert "Kt" to a categorical variable if it appears in split1, split2, or split3
    if "Kt" in [split1, split2, split3]:
        df["Kt"] = pd.Categorical(df["Kt"], categories=["A", "B", "C", "D", "E"])


