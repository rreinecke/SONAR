# Fundamental function to automatically create data sets with a relationship between the variables “X” and “Y”,
  # - which have an arbitrarily adjustable strength
  # - and whose type of relationship can be varied (see type_list):


def create_dataset(r_S, size=1000, xlim_min = 0, xlim_max =1, depth = 1, type ="lin"):
    # Slope and translation term are determined by...
    #   - the interval limits of the X- and Y-variables     (xlim_max - xlim_min), (ylim_max - ylim_min),
    #   - the strength of the relationship,                 (r_S)
    #   - and the combination with a depth factor.          (depth)
    # (see Table 3.4).
    m = r_S * 0.6 * ((depth_faktor) ** (depth - 1))
    n = 0.5-0.5*m
    x1 = np.arange(1, size + 1)
    alpha = 0.001                            # Conditions for significance testing of the correlation ...
    p_value, corr, exit_p = 1, -999, 0       # ... and termination criterion for the while loop.

    while True:
        exit_p = exit_p + 1

        # Relationship with the strength r_S between the variables x1 and x2 ...
        # ... using an independent variable (see subsection 3.3.2):
        SEED(); x2_independent = np.random.normal(0, 1, size)
        x2 = (r_S * (x1 - np.mean(x1)) / np.std(x1) + np.sqrt(1 - r_S ** 2) * x2_independent)

        a, b = np.polyfit(x1, x2, 1)   # Identify the regression line x2 = a*x1+b
        x2 = ((x2 - b) / a) / size          # Normalize to x2 = 1*x1 + 0
        x2 = x2 *m*(xlim_max-xlim_min)      # Adjusting the slope factor to the desired shape
        x2 = x2 + n + m*xlim_min            # Translate the values of the x2-axis to the desired shape
        for i in range(len(x2)):            # Redistribution of all x2 values outside [0, 1]:
            if (x2[i] <= 0) or (x2[i] >1):
                SEED(); x2[i] = np.random.randint(1, 10001) / 10000

        corr, p_value = stats.pearsonr(x1, x2)
        # Checks the strength and significance of the correlation.
        if (p_value <= alpha) & (abs(corr - r_S) < 0.01):
            break
        # Termination criterion if no result is achieved.
        if exit_p >= 1000:
            print("Requirements not satisfied")
            return

    # The monotonic relationships are generated by composition terms that are applied to the linear case
    # (see Table 3.4)
    if type == "lin":
        x2 = x2
        x1 = (x1 * (xlim_max - xlim_min) / size) + xlim_min
    elif type == "squ":     #
        x2 = x2**2
        x1 = (x1 * (xlim_max - xlim_min) / size) + xlim_min
    elif type == "cub":
        x2 = x2**3
        x1 = (x1 * (xlim_max - xlim_min) / size) + xlim_min
    elif type == "exp":
        x2 = (10**x2) / 10
        x1 = (x1 * (xlim_max - xlim_min) / size) + xlim_min
    elif type == "srt":
        x2 = np.sqrt(x2)
        x1 = (x1 * (xlim_max - xlim_min) / size) + xlim_min

    # The non-monotonic correlations arise, analogous to the linear case, directly from the regression curve
    # (see Table 3.4)
    elif type == "sin":
        x1 = (x1 * (xlim_max - xlim_min) / size) + xlim_min
        x2_mean = m/2*np.sin(3 * np.pi * (x1)) + 0.5
        x2 = (r_S * (x2_mean - np.mean(x2_mean)) / np.std(x2_mean)
              + np.sqrt(1 - r_S ** 2) * x2_independent)
        x2 = x2 * np.std(x2_mean) + np.mean(x2_mean)
        for i in range(len(x2)):
            if (x2[i] <= 0) or (x2[i] >1):
                SEED(); x2[i] = np.random.randint(1, 10001) / 10000
    elif type == "ggk":
        x1 = (x1*(xlim_max - xlim_min)/size) + xlim_min
        mu, sigma = 0.5, 0.1  # Default values for mean value and standard deviation
        x2_mean = m * np.exp(-((x1 - mu) ** 2) / (2 * sigma ** 2)) + (0.5 - 0.5 * m)
        x2 = (r_S * (x2_mean - np.mean(x2_mean)) / np.std(x2_mean)
              + np.sqrt(1 - r_S ** 2) * x2_independent)
        x2 = x2 * np.std(x2_mean) + np.mean(x2_mean)
        for i in range(len(x2)):
            if (x2[i] <= 0) or (x2[i] > 1):
                SEED(); x2[i] = np.random.randint(1, 10001) / 10000

    else:
        print(f"Type '{type}' does not exist.")
        exit()

    # Create a panda-df from the variables x1 and x2
    df = pd.DataFrame({'X': x1, 'Y':x2})
    return df

